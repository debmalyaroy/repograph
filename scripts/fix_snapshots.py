# D-053 funnel fix: add the version file a VCS-versioned project generates at install time
# (setuptools_scm write_to / version_file, hatch-vcs version-file, pdm-backend scm write_to) when the snapshot
# lacks it; git never tracks it, so `import pkg` fails in a source checkout (blackjax, pypistats in priv60r2).
# Rewrites <id>.tgz in place (same members, same order, + the stub) and logs every change to fixups.jsonl.
# Usage: uv run python scripts/mining/fix_snapshots.py <snapshots dir> [--ids ids.txt]
import argparse
import io
import json
import tarfile
import tomllib
from pathlib import Path

STUB = ('# generated by the D-053 dataset build (stands in for the VCS version file)\n'
        "__version__ = version = '0.0.0'\n__version_tuple__ = version_tuple = (0, 0, 0)\n"
        'commit_id = __commit_id__ = None\n')


def version_files(pyproject: bytes) -> list[str]:
    try:
        d = tomllib.loads(pyproject.decode('utf-8', 'replace'))
    except (tomllib.TOMLDecodeError, UnicodeError):
        return []
    tool = d.get('tool', {})
    out = []
    scm = tool.get('setuptools_scm', {})
    out += [scm[k] for k in ('write_to', 'version_file') if isinstance(scm.get(k), str)]
    hatch = tool.get('hatch', {})
    for hooks in (hatch.get('build', {}).get('hooks', {}), hatch.get('build', {}).get('targets', {}).get('wheel', {}).get('hooks', {})):
        vf = (hooks.get('vcs') or {}).get('version-file')
        if isinstance(vf, str):
            out.append(vf)
    pdm = tool.get('pdm', {}).get('version', {})
    if isinstance(pdm.get('write_to'), str):
        out.append(pdm['write_to'])
    return [p for p in out if p and p.endswith('.py')]


def fix(tgz: Path) -> list[str]:
    with tarfile.open(tgz, 'r:gz') as t:
        members = t.getmembers()
        names = {m.name.removeprefix('./') for m in members}
        pp = next((m for m in members if m.name.removeprefix('./') == 'pyproject.toml'), None)
        if pp is None:
            return []
        missing = [f for f in version_files(t.extractfile(pp).read()) if f not in names]
        if not missing:
            return []
        prefix = './' if pp.name.startswith('./') else ''
        buf = io.BytesIO()
        with tarfile.open(fileobj=buf, mode='w:gz', format=tarfile.PAX_FORMAT) as o:
            for m in members:
                o.addfile(m, t.extractfile(m) if m.isfile() else None)
            for f in missing:
                data = STUB.encode()
                ti = tarfile.TarInfo(prefix + f)
                ti.size, ti.mode, ti.mtime = len(data), 0o644, pp.mtime
                o.addfile(ti, io.BytesIO(data))
    tmp = tgz.with_suffix('.tgz.tmp')
    tmp.write_bytes(buf.getvalue())
    tmp.replace(tgz)
    return missing


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('snapshots', type=Path)
    ap.add_argument('--ids', type=Path)
    a = ap.parse_args()
    ids = set(a.ids.read_text().split()) if a.ids else None
    log = a.snapshots.parent / 'fixups.jsonl'
    n = 0
    with log.open('a', encoding='utf-8') as f:
        for tgz in sorted(a.snapshots.glob('*.tgz')):
            iid = tgz.name.removesuffix('.tgz')
            if ids is not None and iid not in ids:
                continue
            added = fix(tgz)
            if added:
                n += 1
                f.write(json.dumps({'instance_id': iid, 'fixup': 'version_file', 'files': added}) + '\n')
                print(iid, 'added', added, flush=True)
    print('fixed', n, 'snapshots', flush=True)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
